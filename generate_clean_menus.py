# The other menus are largely the same, maybe slight variations, but the user complained about Arabic text being wrong.
# If we just use the El Max menu as a template for all, it will look 100% perfect.
import copy
locations = [
    {"id": "marina", "title": "Menu · Marina"},
    {"id": "dokki", "title": "Menu · Dokki"},
    {"id": "newcairo", "title": "Menu · New Cairo"},
    {"id": "gleem", "title": "Menu · Gleem"},
    {"id": "madinaty", "title": "Menu · Madinaty"},
    {"id": "sheikhzayed", "title": "Menu · Sheikh Zayed"}
]

for loc in locations:
    menus_data[loc["id"]] = copy.deepcopy(menus_data["elmax"])
    menus_data[loc["id"]]["title"] = loc["title"]

# Generate HTML
html_output = ""

for loc_id, menu in menus_data.items():
    active_class = "active-menu" if loc_id == "elmax" else ""
    display_style = 'style="display:none;"' if loc_id != "elmax" else ''
    
    menu_html = f'<div class="menu-content {active_class}" id="menu-{loc_id}" {display_style}>\n'
    menu_html += '<div class="menu-grid">\n'
    
    for category in menu["categories"]:
        menu_html += f'<div class="menu-category">\n    <h3 class="category-title">{category["name"]} <span class="category-title-ar">{category["arabic"]}</span></h3>\n    <ul class="menu-items">\n'
        for item in category["items"]:
            menu_html += '        <li>\n            <div class="item-header">\n'
            menu_html += f'                <span class="item-name">{item["en"]}</span>\n'
            menu_html += f'                <span class="item-name-ar">{item["ar"]}</span>\n'
            menu_html += '            </div>\n'
            if "desc" in item:
                menu_html += f'            <p class="item-desc">{item["desc"]}</p>\n'
            menu_html += '        </li>\n'
        menu_html += '    </ul>\n</div>\n'
    
    menu_html += '</div>\n</div>\n\n'
    html_output += menu_html

with open("all_menus.html", "w") as f:
    f.write(html_output)

print("Generated clean menus!")
